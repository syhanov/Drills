// Тренажёр M04 — «Предскажи результат». Задание и правила — в index.html.
// Первый аргумент show — номер выражения, по нему сверяешь консоль.
// show печатает строки в кавычках: console.log выводит их без кавычек,
// и '52' в консоли не отличить от 52.
function show(n, value) {
  console.log(n, typeof value === 'string' ? `'${value}'` : value);
}

// 1. предсказание: object
show(1, typeof null);

// 2. предсказание: undifiend 
//    правильно: number    
//    правило: NaN имеет тип number, потому что так определено стандартом плавающей запятой IEEE 754, который использует JavaScript и другие языки программирования.
show(2, typeof NaN);

// 3. предсказание: undifiend
//    правильно: object (Я думал, мы обращаемся к несуществующему элементу какого‑то массива)
//    правило: Массив — это всегда объект: В JavaScript нет отдельного базового типа данных «массив».
show(3, typeof []);

// 4. предсказание: Undifiend
show(4, typeof missingVariable);

// 5. предсказание: true
show(5, '5' == 5);

// 6. предсказание: false
show(6, '5' === 5);

// 7. предсказание: true
show(7, null == undefined);

// 8. предсказание: false
show(8, null === undefined);

// 9. предсказание: true
//    правильно: false
//    правило: Спецификация языка жестко определяет: null == undefined дает true, а null с любым другим значением (включая 0, false, "") всегда дает false.
show(9, null == 0);

// 10. предсказание: true
show(10, null >= 0);

// 11. предсказание: true
//     правльно: false
//     правило: Это одно из самых известных и уникальных исключений в JavaScript (и во многих других языках программирования, использующих стандарт IEEE 754 для чисел с плавающей точкой).
show(11, NaN === NaN);

// 12. предсказание: 0,333333333 (я помнил что получиться подобное число, но не помнил какое точно)
//     правильно: 0.30000000000000004
//     правило: В этом виноват не сам JavaScript, а международный стандарт IEEE 754, по которому компьютеры работают с числами с плавающей точкой.
show(12, 0.1 + 0.2);

// 13. предсказание: false
show(13, 0.1 + 0.2 === 0.3);

// 14. предсказание: 12
//     правильно: NaN
//     правило: Если в строке есть хотя бы один лишний символ, который не является частью математического числа (в данном случае буквы px), функция сдается и возвращает NaN (Not-a-Number), кроме пробелов они сокращаються.
show(14, Number('12px'));

// 15. предсказание: Nan
//     правильно: 12
//     правило: Дойдя до буквы p, parseInt() понимает, что это не цифра. Она просто останавливает сканирование и возвращает все, что успела успешно прочитать до этого момента. Тоесть если бы было (1p2x) вернулось бы 1
show(15, parseInt('12px'));

// 16. предсказание: 52 (забыл дописать ковычки, но имел ввиду строку)
//     правильно: "52"
//     правило: при сложении строки с числом число конвертируеться в строку 
show(16, '5' + 2);

// 17. предсказание: 3
show(17, '5' - 2);

// 18. предсказание: 33
//     правильно: "33"
show(18, 1 + 2 + '3');

// 19. предсказание: Год: Undifiend
show(19, `Год: ${undefined}`);

// 20. предсказание: 1, 9 , 10
//     правльно: 1, 10, 9
//     поавило: JavaScript берет каждое число, неявно превращает его в строку и сравнивает их посимвольно (по таблице Unicode):Он сравнивает первые символы всех элементов: '1' (из 1), '1' (из 10) и '9' (из 9).Символ '1' идет раньше, чем '9'. Поэтому строка '9' сразу улетает в самый конец.Теперь он сравнивает '1' и '10'. Первые символы у них одинаковые ('1'). Тогда он смотрит на второй символ. У числа 1 второго символа нет, а у 10 вторым символом идет '0'. По правилам сортировки строк, более короткая строка '1' встает перед '10'.
show(20, [10, 9, 1].sort());
